"""Pure local-bundle PostgreSQL recovery plan, without execution or authorization.

Every repository operation, including recovery-time WAL retrieval, explicitly
selects the downloaded POSIX repository. A reviewed native executor must prove
the stated conditions and own durable intents, process identities and locks.
"""
import datetime as dt
import hashlib
import json
import re


ROOT = "/var/lib/careertrellis/onedrive-bundles"
RESTORE_ROOT = "/var/lib/careertrellis-onedrive-bundle-acceptance"
CONFIG = "/etc/pgbackrest/pgbackrest.conf"
PG = "/usr/lib/postgresql/18/bin/"
PORT = 55432
LOCKS = ("/var/lib/careertrellis/paired-maintenance/db/control.lock",
         "/run/lock/careertrellis-maintenance.lock",
         "/run/lock/careertrellis-pgbackrest-repository.lock")
UNITS = tuple("careertrellis-pgbackrest-" + name + ".service"
              for name in ("full", "differential", "onedrive", "inventory", "restore"))


class RestoreRefused(ValueError):
    """Privacy-safe plan refusal."""


def need(value):
    if not value:
        raise RestoreRefused("local_bundle_restore_refused")


def canonical(value):
    return (json.dumps(value, sort_keys=True, separators=(",", ":"),
                       ensure_ascii=True, allow_nan=False) + "\n").encode("ascii")


def digest(value):
    return hashlib.sha256(canonical(value)).hexdigest()


def _label(value):
    need(isinstance(value, str) and re.fullmatch(
        r"[0-9]{8}-[0-9]{6}F(?:_[0-9]{8}-[0-9]{6}[DI])?", value))
    labels = value.split("_")
    try:
        dates = [dt.datetime.strptime(label[:-1], "%Y%m%d-%H%M%S") for label in labels]
    except ValueError:
        raise RestoreRefused("local_bundle_restore_refused") from None
    need(len(dates) == 1 or dates[1] > dates[0])
    return labels[0]


def plan(label, archive_sha256, generation_sha256, transaction, max_database_bytes):
    """Return fixed commands and mandatory evidence conditions; never perform IO.

    Private configuration is consumed by path, never copied into this plan. Its
    owner/mode, include paths, executable hooks and absence of remote host/extra
    repository settings need native validation before any command executes.
    """
    ancestor = _label(label)
    need(isinstance(archive_sha256, str) and re.fullmatch("[0-9a-f]{64}", archive_sha256))
    need(isinstance(generation_sha256, str) and re.fullmatch("[0-9a-f]{64}", generation_sha256))
    need(isinstance(transaction, str) and re.fullmatch("[0-9a-f]{32}", transaction))
    need(type(max_database_bytes) is int and 0 < max_database_bytes <= 1024 ** 4)
    transaction_root = ROOT + "/" + transaction
    attempt = RESTORE_ROOT + "/" + transaction
    repository = attempt + "/repository"
    data, socket = attempt + "/data", attempt + "/socket"
    postgres = ["/usr/bin/setpriv", "--reuid=postgres", "--regid=postgres",
                "--init-groups", "--reset-env", "--"]
    local_repository = ["/usr/bin/pgbackrest", "--config=" + CONFIG,
        "--log-level-console=off", "--log-level-file=off",
        "--no-archive-async", "--lock-path=" + attempt + "/pgbackrest-lock",
        "--spool-path=" + attempt + "/pgbackrest-spool",
        "--config-include-path=" + attempt + "/pgbackrest-includes",
        "--repo=1", "--repo1-type=posix", "--repo1-path=" + repository,
        "--stanza=careertrellis"]
    # The WAL recovery command must override settings generated by restore or
    # inherited from the original configuration, retaining the local boundary.
    archive_get = " ".join(local_repository + ["archive-get", "%f", "%p"])
    options = " ".join((
        "-c config_file=" + data + "/postgresql.bundle.conf",
        "-c data_directory=" + data,
        "-c hba_file=" + data + "/pg_hba.bundle.conf",
        "-c ident_file=" + data + "/pg_ident.bundle.conf",
        "-c listen_addresses=", "-c port=" + str(PORT),
        "-c unix_socket_directories=" + socket, "-c unix_socket_group=",
        "-c unix_socket_permissions=0700", "-c ssl=off",
        "-c shared_preload_libraries=", "-c session_preload_libraries=",
        "-c local_preload_libraries=", "-c archive_mode=off",
        "-c archive_command=", "-c archive_cleanup_command=",
        "-c recovery_end_command=", "-c logging_collector=off",
        "-c log_destination=stderr", "-c external_pid_file=",
        "-c primary_conninfo=", "-c primary_slot_name=",
        "-c restore_command='" + archive_get + "'",
        "-c recovery_target=immediate", "-c recovery_target_action=promote",
        "-c recovery_target_timeline=latest",
        "-c max_connections=100", "-c shared_buffers=64MB", "-c jit=off",
        "-c max_logical_replication_workers=0", "-c max_sync_workers_per_subscription=0",
        "-c max_parallel_apply_workers_per_subscription=0", "-c max_parallel_workers=0",
        "-c max_worker_processes=0"))
    return {
        "schema": "careertrellis.onedrive-local-restore-plan/v1",
        "execution_authorized": False, "role": "job-applier-db-staging-01",
        "transaction": transaction, "archive_sha256": archive_sha256,
        "generation_sha256": generation_sha256, "backup_label": label,
        "full_ancestor_label": ancestor, "transaction_root": transaction_root,
        "repository_root": repository, "attempt_root": attempt,
        "repository_input_root": transaction_root + "/downloaded-repository",
        "lock_root": attempt + "/pgbackrest-lock",
        "spool_root": attempt + "/pgbackrest-spool",
        "include_root": attempt + "/pgbackrest-includes",
        "data_root": data, "socket_root": socket, "tablespace_root": attempt + "/tablespaces",
        "port": PORT, "maximum_database_bytes": max_database_bytes,
        "minimum_free_bytes": 2 * max_database_bytes + 512 * 1024 ** 2 + 5 * 1024 ** 3,
        "minimum_free_inodes": 10000, "locks_in_order": list(LOCKS), "idle_units": list(UNITS),
        "info": postgres + local_repository + ["--output=json", "info"],
        "restore": postgres + local_repository + ["--set=" + label, "--pg1-path=" + data,
            "--type=immediate", "--target-action=promote", "--no-link-all",
            "--reset-link-map", "--reset-tablespace-map",
            "--tablespace-map-all=" + attempt + "/tablespaces", "--no-delta", "--force=n", "restore"],
        "archive_get_template": postgres + local_repository + ["archive-get", "%f", "%p"],
        "start": postgres + [PG + "pg_ctl", "--pgdata=" + data, "--options=" + options,
            "--log=" + data + "/postgresql.bundle.log", "--wait", "--timeout=90", "start"],
        "probe": postgres + ["/usr/bin/psql", "-X", "-w", "--quiet", "--host=" + socket,
            "--port=" + str(PORT), "--username=postgres", "--dbname=careertrellis",
            "--set=ON_ERROR_STOP=1", "--tuples-only", "--no-align", "--command=" +
            "SELECT CASE WHEN NOT pg_is_in_recovery() AND current_setting('listen_addresses') = '' "
            "AND current_setting('port') = '55432' THEN 'ok' ELSE 'invalid' END"],
        "stop": postgres + [PG + "pg_ctl", "--pgdata=" + data, "--mode=fast",
                            "--wait", "--timeout=60", "stop"],
        "checksums": postgres + [PG + "pg_checksums", "--check", "--pgdata=" + data],
        "hba": "local all postgres peer\nlocal all all reject\n",
        "config_template": "data_directory = '" + data + "'\nlisten_addresses = ''\nport = 55432\n",
        "ident_template": "",
        "timeouts_seconds": {"info": 60, "restore": 3600, "start": 120,
                             "probe": 5, "stop": 90, "checksums": 600},
        "preconditions": [
            "fresh_root_owned_manifest_binds_downloaded_archive_digest_generation_and_label",
            "archive_digest_and_every_extracted_file_digest_verified_from_downloaded_bytes",
            "downloaded_repository_complete_and_private_with_no_links_or_mount_crossings",
            "protected_existing_pgbackrest_config_validated_without_printing_secret_values",
            "config_has_no_includes_command_hooks_remote_hosts_extra_repositories_or_recovery_overrides",
            "postgres_can_read_config_and_local_repository_without_weakening_permissions",
            "selected_label_and_full_ancestor_present_healthy_in_local_info",
            "database_size_and_hydration_match_bound_receipt",
            "all_ordered_locks_held_and_backup_units_idle_with_empty_cgroups",
            "authority_release_and_schema_unchanged_and_no_activation_lease",
            "attempt_root_absent_and_exclusively_created_with_durable_ownership_intent",
            "sufficient_disk_and_inodes_and_no_existing_socket_or_tcp_55432_listener",
            "postgres_auto_conf_and_recovery_signal_state_validated_before_start",
            "fixed_private_config_hba_ident_and_socket_created_without_inherited_include_files",
            "native_process_identity_and_durable_phase_intent_recorded_before_each_dispatch"],
        "postconditions": [
            "promotion_probe_passes_on_exact_owned_postmaster_with_no_tcp_listener",
            "original_postmaster_terminal_and_process_group_empty_before_offline_checksums",
            "offline_checksums_pass_for_exact_data_root",
            "all_socket_and_pid_files_absent_and_tcp_55432_unbound",
            "terminal_receipt_binds_downloaded_archive_generation_label_plan_digest_and_elapsed_time"],
        "limitations": ["plan_only_no_executor", "no_provider_contact", "no_live_cluster_changes",
                        "no_object_decryption_or_reference_reconciliation", "no_automatic_cleanup"],
    }


def validate_plan(value):
    """Reject tampered commands/paths or extra fields by exact reconstruction."""
    try:
        need(type(value) is dict)
        expected = plan(value["backup_label"], value["archive_sha256"],
            value["generation_sha256"], value["transaction"], value["maximum_database_bytes"])
        need(canonical(value) == canonical(expected))
    except RestoreRefused:
        raise
    except Exception:
        raise RestoreRefused("local_bundle_restore_refused") from None
    return {"result": "validated", "execution_authorized": False, "plan_sha256": digest(value)}
